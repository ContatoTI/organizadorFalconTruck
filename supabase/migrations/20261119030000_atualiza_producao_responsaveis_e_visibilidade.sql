-- 1) Tabelas de compartilhamento (usadas por "Também responsáveis" e "Compartilhar pasta").
create table if not exists public.section_shares (
  id bigint generated by default as identity primary key,
  section_id bigint references public.sections(id) on delete cascade not null,
  user_id uuid references auth.users(id) on delete cascade not null,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  unique(section_id, user_id)
);

create table if not exists public.task_shares (
  id bigint generated by default as identity primary key,
  task_id bigint references public.todos(id) on delete cascade not null,
  user_id uuid references auth.users(id) on delete cascade not null,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  unique(task_id, user_id)
);

alter table public.section_shares enable row level security;
alter table public.task_shares enable row level security;
create index if not exists idx_section_shares_user on public.section_shares(user_id);
create index if not exists idx_task_shares_user on public.task_shares(user_id);

alter table public.todos add column if not exists assignee_id uuid references auth.users(id) on delete set null;

-- 2) Funções de apoio (security definer = não esbarram nas regras das outras tabelas).
create or replace function public.is_project_member(p_project_id bigint, p_user_id uuid)
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.project_members where project_id = p_project_id and user_id = p_user_id)
      or exists (select 1 from public.projects where id = p_project_id and owner_id = p_user_id);
$$;

create or replace function public.participa_do_projeto(p_project_id bigint, p_user_id uuid)
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.projects where id = p_project_id and owner_id = p_user_id)
      or exists (select 1 from public.project_members where project_id = p_project_id and user_id = p_user_id);
$$;

create or replace function public.is_section_shared(p_section_id bigint, p_user_id uuid)
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.section_shares where section_id = p_section_id and user_id = p_user_id);
$$;

create or replace function public.is_task_shared(p_task_id bigint, p_user_id uuid)
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.task_shares where task_id = p_task_id and user_id = p_user_id);
$$;

grant execute on function public.is_project_member(bigint, uuid) to authenticated;
grant execute on function public.participa_do_projeto(bigint, uuid) to authenticated;
grant execute on function public.is_section_shared(bigint, uuid) to authenticated;
grant execute on function public.is_task_shared(bigint, uuid) to authenticated;

-- 3) Quem pode compartilhar: dono da tarefa/pasta ou quem participa do projeto.
--    Quem recebeu pode remover a si mesmo.
drop policy if exists "Task owners manage task shares" on public.task_shares;
create policy "Task owners manage task shares" on public.task_shares
  for all using (
    user_id = auth.uid()
    or exists (select 1 from public.todos t where t.id = task_id
      and (t.user_id = auth.uid() or (t.project_id is not null and public.is_project_member(t.project_id, auth.uid()))))
  )
  with check (
    exists (select 1 from public.todos t where t.id = task_id
      and (t.user_id = auth.uid() or (t.project_id is not null and public.is_project_member(t.project_id, auth.uid()))))
  );

drop policy if exists "Section owners manage section shares" on public.section_shares;
create policy "Section owners manage section shares" on public.section_shares
  for all using (
    user_id = auth.uid()
    or exists (select 1 from public.sections s where s.id = section_id
      and (s.user_id = auth.uid() or public.is_project_member(s.project_id, auth.uid())))
  )
  with check (
    exists (select 1 from public.sections s where s.id = section_id
      and (s.user_id = auth.uid() or public.is_project_member(s.project_id, auth.uid())))
  );

-- 4) Leitura de tarefas: regra única (remove regras antigas de leitura e qualquer RESTRICTIVE).
do $$
declare r record;
begin
  for r in
    select policyname from pg_policies
    where schemaname = 'public' and tablename = 'todos'
      and (cmd = 'SELECT' or permissive = 'RESTRICTIVE')
  loop
    execute format('drop policy if exists %I on public.todos', r.policyname);
  end loop;
end $$;

create policy "todos_select_visiveis" on public.todos
