-- ════════════════════════════════════════════════════════════════════════════
-- 1) A REGRA DE REPETIÇÃO, na própria tarefa
--
--    A tarefa continua sendo UMA linha. O que se repete é a exibição dela:
--    o calendário e a agenda expandem a regra para as datas do período que
--    estão mostrando. Materializar 200 linhas para "toda terça" tornaria
--    impossível editar o compromisso depois.
--
--    A âncora da série é due_at (ou due_date, quando não há hora).
-- ════════════════════════════════════════════════════════════════════════════

ALTER TABLE public.todos
  ADD COLUMN IF NOT EXISTS recur_freq text,
  ADD COLUMN IF NOT EXISTS recur_interval integer DEFAULT 1,
  ADD COLUMN IF NOT EXISTS recur_weekdays jsonb,
  ADD COLUMN IF NOT EXISTS recur_until date,
  ADD COLUMN IF NOT EXISTS recur_count integer;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'todos_recur_freq_check'
  ) THEN
    ALTER TABLE public.todos
      ADD CONSTRAINT todos_recur_freq_check
      CHECK (recur_freq IS NULL OR recur_freq IN ('daily', 'weekly', 'monthly', 'yearly'));
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'todos_recur_interval_check'
  ) THEN
    ALTER TABLE public.todos
      ADD CONSTRAINT todos_recur_interval_check
      CHECK (recur_interval IS NULL OR (recur_interval >= 1 AND recur_interval <= 365));
  END IF;
END $$;

COMMENT ON COLUMN public.todos.recur_freq IS
  'daily | weekly | monthly | yearly. NULL = compromisso único.';
COMMENT ON COLUMN public.todos.recur_interval IS
  'A cada quantos períodos: 2 + weekly = a cada duas semanas.';
COMMENT ON COLUMN public.todos.recur_weekdays IS
  'Só para weekly: [2] = toda terça, [1,3,5] = seg/qua/sex. NULL = usa o dia da âncora.';
COMMENT ON COLUMN public.todos.recur_until IS
  'Último dia da série. NULL = não acaba.';
COMMENT ON COLUMN public.todos.recur_count IS
  'Limite de ocorrências. NULL = sem limite. Vence recur_until quando os dois existem.';

CREATE INDEX IF NOT EXISTS idx_todos_recurring
  ON public.todos (user_id, recur_freq)
  WHERE deleted_at IS NULL AND recur_freq IS NOT NULL;


-- ════════════════════════════════════════════════════════════════════════════
-- 2) O QUE ACONTECEU EM CADA OCORRÊNCIA
--
--    Tabela esparsa de propósito: só existe linha para a data em que você fez
--    alguma coisa (concluiu, pulou ou mudou de horário). Uma série semanal de
--    dois anos que você nunca tocou não ocupa uma linha sequer.
-- ════════════════════════════════════════════════════════════════════════════

CREATE TABLE IF NOT EXISTS public.todo_occurrences (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  task_id bigint REFERENCES public.todos(id) ON DELETE CASCADE NOT NULL,
  user_id uuid REFERENCES auth.users NOT NULL DEFAULT auth.uid(),
  -- O dia da ocorrência na série original, mesmo que ela tenha sido movida.
  occurrence_date date NOT NULL,
  is_completed boolean DEFAULT false NOT NULL,
  completed_at timestamp with time zone,
  -- "Nesta semana não" sem apagar a série.
  is_skipped boolean DEFAULT false NOT NULL,
  -- Só esta ocorrência mudou de horário.
  moved_to timestamp with time zone,
  created_at timestamp with time zone DEFAULT timezone('utc'::text, now()) NOT NULL,
  CONSTRAINT todo_occurrences_unique UNIQUE (task_id, occurrence_date)
);

CREATE INDEX IF NOT EXISTS idx_todo_occurrences_task
  ON public.todo_occurrences (task_id, occurrence_date DESC);
CREATE INDEX IF NOT EXISTS idx_todo_occurrences_user_date
  ON public.todo_occurrences (user_id, occurrence_date DESC);

ALTER TABLE public.todo_occurrences ENABLE ROW LEVEL SECURITY;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename = 'todo_occurrences' AND policyname = 'todo_occurrences_select_own') THEN
    CREATE POLICY "todo_occurrences_select_own" ON public.todo_occurrences FOR SELECT USING (auth.uid() = user_id);
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename = 'todo_occurrences' AND policyname = 'todo_occurrences_insert_own') THEN
    CREATE POLICY "todo_occurrences_insert_own" ON public.todo_occurrences FOR INSERT WITH CHECK (auth.uid() = user_id);
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename = 'todo_occurrences' AND policyname = 'todo_occurrences_update_own') THEN
    CREATE POLICY "todo_occurrences_update_own" ON public.todo_occurrences FOR UPDATE USING (auth.uid() = user_id);
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename = 'todo_occurrences' AND policyname = 'todo_occurrences_delete_own') THEN
    CREATE POLICY "todo_occurrences_delete_own" ON public.todo_occurrences FOR DELETE USING (auth.uid() = user_id);
  END IF;
END $$;


-- ════════════════════════════════════════════════════════════════════════════
